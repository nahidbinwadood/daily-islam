# Builds learn-data.js: the recitations for the wudu and salah guides, copied verbatim from their sources.
# Religious text is never typed by hand. Hisnul Muslim sends no CORS header, so the browser cannot fetch it
# live; this script snapshots it instead. Run: python learn-data.py  (needs internet)
import json, re, urllib.request
from datetime import date

HISN = 'https://www.hisnmuslim.com/api/en/{}.json'
HADITH = 'https://cdn.jsdelivr.net/gh/fawazahmed0/hadith-api@1/editions/{}/{}.json'
# key -> (Hisnul Muslim chapter, entry id)
PICK = {
    'bismillah': (8, 12), 'wuduEnd': (9, 13), 'wuduEnd2': (9, 14),
    'sana': (16, 28), 'taawwudh': (82, 193), 'ruku': (17, 33), 'qawmah': (18, 38), 'qawmah2': (18, 39),
    'sujud': (19, 41), 'jalsah': (20, 48), 'tashahhud': (22, 52), 'durood': (23, 53), 'duaMasura': (24, 57),
    'afterIstighfar': (25, 66), 'afterTasbih': (25, 69),
}
DIAC = '[ً-ْٰ]*'

def get(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})  # hisnmuslim.com refuses Python's default
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode('utf-8-sig'), strict=False)

def phrase(text, plain):
    """the first place `plain` (no harakat) occurs in `text`, harakat kept as the source has them"""
    pat = ''.join(re.escape(c) + DIAC if c != ' ' else r'\s+' for c in plain)
    return re.search(pat, text).group(0)

def clean(s):
    s = re.sub(r'^[\s(]+|[\s).]+$', '', s.replace('((', '').replace('))', ''))
    return re.sub(r'[\s.]*ثلاث\S*(\s+مر\S*)?[\s.]*$', '', s).strip(' .')  # the count is kept in `repeat`

def en(s):
    s = s.split(')(')[0]  # drop the translator's footnotes
    return re.sub(r'\s+', ' ', re.sub(r'’?\s*\(three times\)?\)?', '', s)).strip(' ()’.') + '.'

out, chapters = {}, {}
for key, (ch, eid) in PICK.items():
    chapters.setdefault(ch, get(HISN.format(ch)))
    title, rows = next(iter(chapters[ch].items()))
    e = next(r for r in rows if r['ID'] == eid)
    out[key] = {'ar': clean(e['ARABIC_TEXT']), 'en': en(e['TRANSLATED_TEXT']), 'repeat': e['REPEAT'],
                'audio': e['AUDIO'].replace('http://', 'https://'), 'src': f'হিসনুল মুসলিম, অধ্যায় {ch}, নং {eid}'}

# sub-phrases, cut from a longer source text by script
qawmah2 = out['qawmah2']
qawmah2['ar'] = phrase(qawmah2['ar'], 'ربنا ولك الحمد')
qawmah2['en'] = ','.join(qawmah2['en'].split(',')[:2]) + '.'
qawmah2.pop('audio')  # the audio is the full, longer wording
t31 = next(r for r in next(iter(chapters[16].values())) if r['ID'] == 31)
out['takbir'] = {'ar': phrase(t31['ARABIC_TEXT'], 'الله أكبر'), 'en': t31['TRANSLATED_TEXT'].strip(' (').split(',')[0] + '.',
                 'repeat': 1, 'src': 'হিসনুল মুসলিম, অধ্যায় 16, নং 31 থেকে'}
ad = get(HADITH.format('ara-abudawud', 996))['hadiths'][0]
adbn = get(HADITH.format('ben-abudawud', 996))['hadiths'][0]
out['salam'] = {'ar': phrase(ad['text'], 'السلام عليكم ورحمة الله'), 'repeat': 1, 'bnSaid': re.search(r'‘?আসসালামু[^’]*রহমাতুল্লাহ', adbn['text']).group(0).lstrip('‘'),
                'src': f"সুনান আবু দাউদ {ad['hadithnumber']} (আলবানি: {adbn['grades'][0]['grade']})"}

js = ('// GENERATED by learn-data.py on ' + date.today().isoformat() + ' from hisnmuslim.com and fawazahmed0/hadith-api.\n'
      '// Do not edit by hand: Arabic, English and audio are verbatim from the source named in `src`.\n'
      'const RECITE = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
open('learn-data.js', 'w', encoding='utf-8', newline='\n').write(js)
print('wrote', len(out), 'recitations')
